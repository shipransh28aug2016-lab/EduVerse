// Generates sw.js: a small service worker so the app works offline and on slow networks after the first visit.
// Precaches the app shell and every module/data file except the heavy three.js build (cached on first 3-D use).
// Strategy: stale-while-revalidate for same-origin GET (fast from cache, refreshed in the background). Re-run after adding files.
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
const roots = ['index.html', 'assets', 'src', 'data'], files = [];
const walk = (p) => { for (const e of fs.readdirSync(p, { withFileTypes: true })) { const f = path.join(p, e.name); if (e.isDirectory()) walk(f); else if (!/\.(md|png|pdf)$/.test(e.name)) files.push(f.replaceAll('\\', '/')); } };
for (const r of roots) fs.statSync(r).isDirectory() ? walk(r) : files.push(r);
files.sort();
const hash = crypto.createHash('sha1').update(files.map((f) => f + fs.statSync(f).size).join('|')).digest('hex').slice(0, 10);
fs.writeFileSync('sw.js', `// GENERATED by tools/build-sw.mjs — do not edit. Cache version ${hash}.
const CACHE = 'eduverse-${hash}';
const PRECACHE = ${JSON.stringify(['./', ...files], null, 1)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('eduverse-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== 'GET' || u.origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async (c) => {
    const hit = await c.match(r, { ignoreSearch: true });
    const net = fetch(r).then((res) => { if (res.ok) c.put(r, res.clone()); return res; }).catch(() => hit);
    return hit || net;
  }));
});
`);
console.log(`sw.js: ${files.length} files precached, version ${hash}`);
